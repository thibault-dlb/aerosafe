from datetime import datetime
from typing import Annotated, Literal

from pydantic import BaseModel, BeforeValidator, ConfigDict, Field

# Simple shape check only: there is no e-mail verification (team decision).
EMAIL_PATTERN = r"^[^@\s]+@[^@\s]+\.[^@\s]+$"

Email = Annotated[
    str,
    Field(max_length=254, pattern=EMAIL_PATTERN),
    BeforeValidator(lambda value: value.strip().lower() if isinstance(value, str) else value),
]
# OWASP: length only, no composition rules.
NewPassword = Annotated[str, Field(min_length=12, max_length=128)]

RoleName = Literal["USER", "SUPERVISOR"]


class UserRead(BaseModel):
    """An account as the API shows it. `id` is the public ULID, never the internal key."""

    id: str = Field(description="Public identifier (ULID)")
    email: str
    role: str = Field(description="Role code: USER or SUPERVISOR")
    is_active: bool
    must_change_password: bool = Field(
        default=False,
        description="The password was generated by a Supervisor: its owner must replace it",
    )


class AccountRead(UserRead):
    """An account in the list of the Supervisor, anonymised ones included."""

    is_anonymised: bool = Field(description="The account no longer identifies anybody")
    created_at: datetime


class AccountPage(BaseModel):
    """One page of accounts and the number of accounts matching the search."""

    model_config = ConfigDict(frozen=True)

    items: list[AccountRead]
    total: int = Field(description="Number of accounts matching the search, all pages included")


class AccountCreate(BaseModel):
    email: Email
    role: RoleName = Field(default="USER", description="Role of the new account")


class AccountCreated(BaseModel):
    """The new account and its provisional password, shown only once."""

    account: AccountRead
    temporary_password: str = Field(
        description="Provisional password: the API keeps no copy, so it is never shown again"
    )


class AccountUpdate(BaseModel):
    """Changes to an account: the fields that are absent stay as they are."""

    role: RoleName | None = None
    is_active: bool | None = None


class PasswordChange(BaseModel):
    current_password: Annotated[str, Field(min_length=1, max_length=128)]
    new_password: NewPassword


class PasswordConfirmation(BaseModel):
    """The password of the caller, asked again before an irreversible action."""

    password: Annotated[str, Field(min_length=1, max_length=128)]
